# =====================================================================
# CHATBOT APPLICATION SYSTEM
# =====================================================================

api_key_input = st.sidebar.text_input("Google Gemini API Key Dalein:", type="password")

if "messages" not in st.session_state:
    st.session_state.messages = []

for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])

if prompt := st.chat_input("Apna sawal yahan puchein (e.g., मलय चंदन का प्राइस क्या है?)..."):
    with st.chat_message("user"):
        st.markdown(prompt)
    st.session_state.messages.append({"role": "user", "content": prompt})

    with st.chat_message("assistant"):
        response_placeholder = st.empty()
        
        if not api_key_input:
            st.error("Kripya sidebar mein Google Gemini API Key dalein!")
        else:
            try:
                import google.generativeai as genai
                genai.configure(api_key=api_key_input)
                
                model = genai.GenerativeModel(
                    model_name="gemini-3.1-flash-lite",
                    system_instruction=STRICT_RULES
                )
                
                response = model.generate_content(prompt)
                full_response = response.text
                response_placeholder.markdown(full_response)
                
                st.session_state.messages.append({"role": "assistant", "content": full_response})
            except Exception as e:
                st.error(f"Error: {str(e)}")
